namespace Wireloom.Dds.Generator.Tests;

public sealed class GeneratedSourceWriterSpecs
{
    [Fact]
    public void OwnsTheGeneratedDocumentLayout()
    {
        var writer = new Wireloom.GeneratedSourceWriter(
            "Sample.Namespace",
            new[] { "Zeta", "Alpha" },
            "sample.idl");

        writer.WriteComment("a comment");
        writer.WriteXmlSummary("A documented member.");
        writer.OpenBlock("public class Sample");
        writer.WriteLine("public int Value { get; set; }");
        writer.CloseBlock();

        writer.ToString().ShouldBe(
            "// <auto-generated/>\n" +
            "// This file was generated by Wireloom from 'sample.idl'.\n" +
            "// Do not modify it directly; update the IDL source and rebuild.\n" +
            "// It requires the RTI Connext DDS .NET runtime.\n" +
            "#nullable enable\n\n" +
            "using Alpha;\n" +
            "using Zeta;\n\n" +
            "namespace Sample.Namespace;\n\n" +
            "// a comment\n" +
            "/// <summary>\n" +
            "/// A documented member.\n" +
            "/// </summary>\n" +
            "public class Sample\n" +
            "{\n" +
            "    public int Value { get; set; }\n" +
            "}\n");
    }
}
