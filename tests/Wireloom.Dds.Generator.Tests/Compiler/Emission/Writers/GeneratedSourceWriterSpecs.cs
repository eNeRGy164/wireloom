namespace Wireloom.Compiler.Emission.Writers.Tests;

public sealed class GeneratedSourceWriterSpecs
{
    [Fact]
    public void OwnsTheGeneratedDocumentLayout()
    {
        // Arrange
        var writer = new GeneratedSourceWriter("Sample.Namespace", new[] { "Zeta", "Alpha" }, "sample.idl");

        writer.WriteComment("a comment");
        writer.WriteXmlSummary("A documented member.");
        writer.OpenBlock("public class Sample");
        writer.WriteLine("public int Value { get; set; }");
        writer.CloseBlock();

        // Act
        var source = writer.ToString();

        // Assert
        var expected =
            """
            // <auto-generated/>
            // This file was generated by Wireloom from 'sample.idl'.
            // Do not modify it directly; update the IDL source and rebuild.
            // It requires the RTI Connext DDS .NET runtime.
            #nullable enable

            using Alpha;
            using Zeta;

            namespace Sample.Namespace;

            // a comment
            /// <summary>
            /// A documented member.
            /// </summary>
            public class Sample
            {
                public int Value { get; set; }
            }
            """
        .TrimEnd().ReplaceLineEndings("\n") + "\n";

        source.ShouldBe(expected);
    }

    [Fact]
    public void EscapesCodeInsideXmlDocumentationExamples()
    {
        // Arrange
        var writer = new GeneratedSourceWriter(null, [], "sample.idl");

        // Act
        writer.WriteXmlExample("if (value < 2 && value > 0) { }");

        // Assert
        writer.ToString().ShouldContain("/// if (value &lt; 2 &amp;&amp; value &gt; 0) { }");
    }
}
