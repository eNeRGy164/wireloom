using System.Text.RegularExpressions;

namespace Wireloom.Dds.Generator.WireCompatibility.Runner;

/// <summary>Discovers typed case descriptors from generated TypeSupport sources and shared manifest metadata.</summary>
/// <param name="catalog">The invocation's corpus metadata snapshot.</param>
internal sealed class WireloomTypeDiscovery(CorpusCaseCatalog catalog)
{
    /// <summary>Discovers previously selected eligible cases in selection order without writing a registry.</summary>
    /// <exception cref="InvalidOperationException">A selected case has no support or its required root is absent.</exception>
    internal IReadOnlyList<CaseDescriptor> Discover(string generatedDirectory, IReadOnlyList<string> caseIds)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(generatedDirectory);
        ArgumentNullException.ThrowIfNull(caseIds);

        var metadata = caseIds.ToDictionary(id => id, catalog.Get, StringComparer.Ordinal);
        var byIdl = metadata.GroupBy(item => Path.GetFileName(item.Value.Idl), StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.Select(item => item.Key).ToArray(), StringComparer.Ordinal);

        foreach (var (caseId, wrapper) in new[]
        {
            ("14-autoid-scope", "14-autoid-scope-topic.idl"),
            ("14-enum-constant", "14-enum-constant-topic.idl"),
        })
        {
            if (metadata.ContainsKey(caseId))
            {
                byIdl[wrapper] = [caseId];
            }
        }

        var candidates = caseIds.ToDictionary(id => id, _ => new List<string>(), StringComparer.Ordinal);
        ReadCandidates(generatedDirectory, byIdl, candidates);

        return [.. caseIds.Select(id => Describe(id, metadata[id].Idl, candidates[id]))];
    }

    private static void ReadCandidates(string directory, Dictionary<string, string[]> byIdl, Dictionary<string, List<string>> candidates)
    {
        foreach (var source in Directory.Exists(directory) ? Directory.EnumerateFiles(directory, "*.g.cs", SearchOption.AllDirectories) : [])
        {
            var text = File.ReadAllText(source);
            var header = Regex.Match(text, "generated by Wireloom from '([^']+)'");
            var support = Regex.Match(text, @"class\s+\w+\s*:\s*TypeSupport<\s*([\w.]+)\s*>");
            if (!header.Success || !support.Success || !byIdl.TryGetValue(header.Groups[1].Value, out var ids))
            {
                continue;
            }

            var namespaceMatch = Regex.Match(text, @"^namespace\s+([\w.]+)\s*;", RegexOptions.Multiline);
            var type = support.Groups[1].Value;
            if (namespaceMatch.Success && !type.Contains('.'))
            {
                type = $"{namespaceMatch.Groups[1].Value}.{type}";
            }

            foreach (var id in ids)
            {
                candidates[id].Add(type);
            }
        }
    }

    private static CaseDescriptor Describe(string caseId, string idl, IReadOnlyList<string> candidates)
    {
        if (candidates.Count == 0)
        {
            throw new InvalidOperationException($"No generated type support found for positive case {caseId}.");
        }

        var requiredRoot = RequiredRoot(caseId);
        if (requiredRoot is not null && candidates.All(type => type.Split('.').Last() != requiredRoot))
        {
            throw new InvalidOperationException($"Case {caseId} requires generated topic root {requiredRoot}, but that type was not emitted from the selected IDL input.");
        }

        var selectedType = candidates.OrderBy(type => RootRank(type, requiredRoot)).ThenBy(type => type, StringComparer.Ordinal).First();
        return new CaseDescriptor(caseId, selectedType, "::" + selectedType.Replace(".", "::", StringComparison.Ordinal), idl);
    }

    private static int RootRank(string type, string? requiredRoot)
    {
        var name = type.Split('.').Last();
        if (name == requiredRoot)
        {
            return -1;
        }

        return name switch
        {
            "Sample" => 0,
            "Composed" => 1,
            _ => 2,
        };
    }

    private static string? RequiredRoot(string caseId) => caseId switch
    {
        "03-enums-aliases" => "Record",
        "02-multiple" => "WireloomWireCompatibilityMultipleTypes",
        "03-enum-values-prefix" or "03-enum-values-explicit" => "EnumTopic",
        "09-optional-recursive-array" => "Node",
        "09-optional-aggregate-member" => "Holder",
        "07-union-aliases" or "06-valuetypes" => "Holder",
        "10-default-literal-enum-array" => "Shape",
        "14-autoid-scope" => "AutoIdScopeSample",
        "14-union-scoped-enum" => "ScopedEnum",
        "14-typed-defaults" => "TypedDefaults",
        "14-enum-constant" => "EnumConstantSample",
        "04-unbounded-string-aliases" => "StringAliasesSample",
        "05-unbounded-sequence-aliases" => "SequenceAliasesSample",
        "04-string-alias-chains" => "StringAliasChainsSample",
        "07-union-string-sequence-aliases" => "StringSequenceUnionsSample",
        "07-union-char-numeric" or "07-union-char-numeric-255" => "Choice",
        "07-union-string-sequence-bounded-direct" => "DirectBoundedStringSequences",
        "08-key-inherited" => "Derived",
        "08-key-nested" => "Outer",
        _ => null,
    };
}
