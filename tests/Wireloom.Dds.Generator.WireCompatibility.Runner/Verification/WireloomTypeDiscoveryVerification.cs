using System.Text.Json.Nodes;

namespace Wireloom.Dds.Generator.WireCompatibility.Runner;

/// <summary>Checks typed Wireloom discovery, required roots, and standalone registry compatibility.</summary>
internal static class WireloomTypeDiscoveryVerification
{
    /// <summary>Verifies discovery without building utilities or writing an intermediate registry.</summary>
    internal static void Run(MatrixOptions options)
    {
        var root = Path.Combine(options.ScratchDirectory, "wireloom-discovery-verification");
        VerifyDescriptors(root);
        VerifyRequiredRoots(root);
        Console.WriteLine("Wireloom discovery passed: typed descriptors, shared IDL, namespaces, root preferences, wrappers, missing support, and registry compatibility; no runtime registry handoff required.");
    }

    private static void VerifyDescriptors(string root)
    {
        // Arrange
        Directory.CreateDirectory(root);
        var manifest = Path.Combine(root, "manifest.json");
        File.WriteAllText(manifest, """
            { "positiveCases": [
              { "id": "plain", "idl": "idl/shared.idl" },
              { "id": "alias", "idl": "idl/shared.idl", "defines": [ "Z=1", "A", "Z=1" ] },
              { "id": "qualified", "idl": "idl/qualified.idl" },
              { "id": "fallback", "idl": "idl/fallback.idl" },
              { "id": "missing", "idl": "idl/missing.idl" }
            ] }
            """);
        var catalog = new CorpusCaseCatalog(manifest);
        var discovery = new WireloomTypeDiscovery(catalog);
        var generated = Path.Combine(root, "generated");
        WriteSupport(generated, "z.g.cs", "shared.idl", "Sample", "Zeta");
        WriteSupport(generated, "nested/a.g.cs", "shared.idl", "Sample", "Alpha");
        WriteSupport(generated, "composed.g.cs", "shared.idl", "Composed", "Alpha");
        WriteSupport(generated, "qualified.g.cs", "qualified.idl", "Exact.Qualified", "Ignored");
        WriteSupport(generated, "fallback-z.g.cs", "fallback.idl", "Zeta.Type");
        WriteSupport(generated, "fallback-a.g.cs", "fallback.idl", "Alpha.Type");
        WriteSupport(generated, "ignored.cs", "shared.idl", "Sample", "A");
        WriteSupport(generated, "unrelated.g.cs", "unrelated.idl", "Sample", "A");
        File.WriteAllText(Path.Combine(generated, "no-header.g.cs"), "class Support : TypeSupport<A.Sample> {}");
        File.WriteAllText(Path.Combine(generated, "no-support.g.cs"), "// generated by Wireloom from 'shared.idl'\nnamespace A;");

        // Act
        var descriptors = discovery.Discover(generated, ["alias", "qualified", "plain", "fallback"]);
        File.Delete(manifest);
        var repeated = discovery.Discover(generated, ["plain"]);

        // Assert
        Check(descriptors.Select(item => item.CaseId).SequenceEqual(["alias", "qualified", "plain", "fallback"], StringComparer.Ordinal), "Descriptor order must follow selection order.");
        Check(descriptors[0] == new CaseDescriptor("alias", "Alpha.Sample", "::Alpha::Sample", "idl/shared.idl"), "Shared IDL aliases must retain namespace qualification, defaults, ordinal ties, and canonical IDL.");
        Check(descriptors[1].WireloomType == "Exact.Qualified" && descriptors[1].CppType == "::Exact::Qualified", "Qualified support types must not receive a second namespace prefix.");
        Check(descriptors[2] == repeated.Single() && descriptors[3].WireloomType == "Alpha.Type", "Repeated discovery must use the metadata snapshot and deterministic fallback.");
        Check(!File.Exists(Path.Combine(generated, "case.json")), "Discovery must not write a runtime registry.");
        CheckRejected<InvalidOperationException>(() => discovery.Discover(generated, ["missing"]), "A selected case without matching support must fail.");
        CheckRejected<InvalidOperationException>(() => discovery.Discover(Path.Combine(root, "absent"), ["plain"]), "A missing generated directory must fail with missing support.");
        Check(discovery.Discover(generated, []).Count == 0, "An empty standalone selection must retain an empty registry result.");

        // Arrange: only the standalone adapter writes a registry.
        var registry = Path.Combine(root, "standalone", "cases.json");

        // Act
        CaseRegistry.Write(descriptors, registry);

        // Assert
        var entries = JsonNode.Parse(File.ReadAllText(registry))!["cases"]!.AsArray();
        Check(entries.Count == 4 && entries[0]!.AsObject().Count == 3 && (string?)entries[0]!["csharpType"] == "Alpha.Sample", "The standalone registry must retain its original schema and case order.");
        Check(File.ReadAllText(registry).EndsWith('\n'), "The standalone registry must retain its trailing newline.");

        // Arrange / Act / Assert
        var composed = Path.Combine(root, "composed");
        WriteSupport(composed, "composed.g.cs", "shared.idl", "Composed");
        WriteSupport(composed, "other.g.cs", "shared.idl", "Other");
        Check(discovery.Discover(composed, ["plain"]).Single().WireloomType == "Composed", "Composed must precede the ordinal fallback when Sample is absent.");
    }

    private static void VerifyRequiredRoots(string root)
    {
        // Arrange
        var roots = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["03-enums-aliases"] = "Record", ["02-multiple"] = "WireloomWireCompatibilityMultipleTypes",
            ["03-enum-values-prefix"] = "EnumTopic", ["03-enum-values-explicit"] = "EnumTopic",
            ["09-optional-recursive-array"] = "Node", ["09-optional-aggregate-member"] = "Holder",
            ["07-union-aliases"] = "Holder", ["06-valuetypes"] = "Holder", ["10-default-literal-enum-array"] = "Shape",
            ["14-autoid-scope"] = "AutoIdScopeSample", ["14-union-scoped-enum"] = "ScopedEnum",
            ["14-typed-defaults"] = "TypedDefaults", ["14-enum-constant"] = "EnumConstantSample",
            ["04-unbounded-string-aliases"] = "StringAliasesSample", ["05-unbounded-sequence-aliases"] = "SequenceAliasesSample",
            ["04-string-alias-chains"] = "StringAliasChainsSample", ["07-union-string-sequence-aliases"] = "StringSequenceUnionsSample",
            ["07-union-char-numeric"] = "Choice", ["07-union-char-numeric-255"] = "Choice",
            ["07-union-string-sequence-bounded-direct"] = "DirectBoundedStringSequences",
            ["08-key-inherited"] = "Derived", ["08-key-nested"] = "Outer",
        };
        foreach (var (caseId, required) in roots)
        {
            var directory = Path.Combine(root, "required", caseId);
            var manifest = Path.Combine(directory, "manifest.json");
            Directory.CreateDirectory(directory);
            File.WriteAllText(manifest, $$"""{ "positiveCases": [ { "id": "{{caseId}}", "idl": "idl/{{caseId}}.idl" } ] }""");
            var discovery = new WireloomTypeDiscovery(new CorpusCaseCatalog(manifest));
            var generated = Path.Combine(directory, "generated");
            WriteSupport(generated, "sample.g.cs", caseId + ".idl", "Sample", "Oracle");

            // Act / Assert
            CheckRejected<InvalidOperationException>(() => discovery.Discover(generated, [caseId]), $"Missing required root {required} must not silently select Sample.");
            var header = caseId is "14-autoid-scope" or "14-enum-constant" ? caseId + "-topic.idl" : caseId + ".idl";
            WriteSupport(generated, "selected.g.cs", header, required, "Oracle");
            Check(discovery.Discover(generated, [caseId]).Single().WireloomType == "Oracle." + required, $"Required root or wrapper mapping changed for {caseId}.");
        }
    }

    private static void WriteSupport(string directory, string relativePath, string idl, string type, string? sourceNamespace = null)
    {
        var path = Path.Combine(directory, relativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        var namespaceLine = sourceNamespace is null ? "" : $"namespace {sourceNamespace};\n";
        File.WriteAllText(path, $"// This file was generated by Wireloom from '{idl}'.\n{namespaceLine}class Support : TypeSupport<{type}> {{ }}");
    }

    private static void CheckRejected<TException>(Action action, string message) where TException : Exception
    {
        try
        {
            action();
        }
        catch (TException)
        {
            return;
        }

        throw new InvalidOperationException(message);
    }

    private static void Check(bool condition, string message)
    {
        if (!condition)
        {
            throw new InvalidOperationException(message);
        }
    }
}
