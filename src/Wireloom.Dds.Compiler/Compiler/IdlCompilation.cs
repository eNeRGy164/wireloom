using Wireloom.Compiler.Emission;
using Wireloom.Compiler.FrontEnd.Parsing;
using Wireloom.Compiler.FrontEnd.Preprocessing;
using Wireloom.Compiler.FrontEnd.Symbols;

namespace Wireloom.Compiler;

/// <summary>Coordinates input traversal, declaration parsing, and emission.</summary>
internal sealed class IdlCompilation(IReadOnlyList<IdlInput> inputs, RtiApiProfile profile, Func<byte[], byte[]> computeMd5, CancellationToken cancellationToken)
{
    public IReadOnlyList<GeneratedIdlSource> Run(ICollection<IdlDiagnostic>? diagnostics = null)
    {
        var comparer = Path.DirectorySeparatorChar == '\\'
            ? StringComparer.OrdinalIgnoreCase
            : StringComparer.Ordinal;
        var files = new Dictionary<string, IdlInput>(comparer);
        var roots = inputs.Where(input => input.Generate).ToArray();

        foreach (var file in inputs)
        {
            if (file.SequenceArrayMapping is not IdlSequenceArrayMapping.RtiCSharp and not IdlSequenceArrayMapping.Idl)
            {
                throw new IdlException(file, 0, "SequenceArrayMapping must be 'RtiCSharp' or 'Idl'.");
            }

            files[Path.GetFullPath(file.Path)] = file;
        }

        var escapeSettings = roots.Select(input => input.EnableEscapeChar).Distinct().ToArray();
        if (escapeSettings.Length > 1)
        {
            throw new IdlException(roots[0], 0, "EnableEscapeChar must have the same value for every generation root in a compilation batch.");
        }

        var enableEscapeChar = escapeSettings.FirstOrDefault();
        var symbols = new IdlSymbolTable();
        var graph = new IdlInputGraph(files, roots.SelectMany(input => input.Defines), roots.SelectMany(input => input.Undefines), roots.SelectMany(input => input.IncludeDirectories), cancellationToken, enableEscapeChar);
        var parser = new IdlDeclarationParser(symbols, cancellationToken, computeMd5, diagnostics);
        var result = new EmissionResult();
        var compilation = new CompilationContext(symbols);

        // Roots are sorted by path so generation is stable even when the build
        // system supplies AdditionalFiles in a different order.
        foreach (var input in roots.OrderBy(input => input.Path, StringComparer.Ordinal))
        {
            graph.BeginRoot();
            graph.Visit(input, (text, file, offset, currentNamespace, origins, escapedIdentifierOffsets) =>
                parser.Parse(text, file, offset, currentNamespace, origins, escapedIdentifierOffsets), diagnostics);
        }

        parser.Bind();
        var strict = inputs.Any(input => input.Generate && input.Strict);
        parser.Validate(strict);

        if (!profile.SupportsMustUnderstand)
        {
            foreach (var member in parser.Declarations
                         .SelectMany(GetMembers)
                         .Where(member => member.Metadata.IsMustUnderstand && member.SourceInput is not null))
            {
                diagnostics?.Add(new IdlDiagnostic(
                    "DDSG0004",
                    member.SourceInput!,
                    member.SourceOffset,
                    $"The @must_understand annotation is not supported by the RTI {profile.RtiVersion} API profile generated by rtiddsgen {profile.RtiddsgenVersion}."));
            }

            if (parser.Declarations.SelectMany(GetMembers).Any(member => member.Metadata.IsMustUnderstand))
            {
                return [];
            }
        }

        var sequenceArrays = new Emission.Planning.SequenceArrayEmissionPlan(compilation, symbols, parser.Declarations, profile);
        return new IdlDeclarationEmitter(compilation, parser.Declarations, result, profile, sequenceArrays).Emit();
    }

    private static IEnumerable<FrontEnd.Semantic.IdlMember> GetMembers(FrontEnd.Semantic.IdlDeclaration declaration) => declaration switch
    {
        FrontEnd.Semantic.IdlClassDeclaration classDeclaration => classDeclaration.Fields,
        FrontEnd.Semantic.IdlUnionDeclaration unionDeclaration => unionDeclaration.Declaration.Branches.Select(branch => branch.Field),
        _ => []
    };
}
