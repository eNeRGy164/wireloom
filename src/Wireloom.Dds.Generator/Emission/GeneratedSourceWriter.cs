using System.Text;

namespace Wireloom;

/// <summary>
/// Writes deterministic generated C# source while owning its layout.
/// </summary>
internal sealed class GeneratedSourceWriter
{
    private const string IndentText = "    ";
    private readonly StringBuilder output = new();
    private int indentation;

    public GeneratedSourceWriter(
        string? currentNamespace,
        IEnumerable<string> usingDirectives,
        string sourceIdlFileName)
    {
        WriteComment("<auto-generated/>");
        WriteComment($"This file was generated by Wireloom from '{sourceIdlFileName}'.");
        WriteComment("Do not modify it directly; update the IDL source and rebuild.");
        WriteComment("It requires the RTI Connext DDS .NET runtime.");
        WriteLine("#nullable enable");
        BlankLine();

        foreach (var usingDirective in usingDirectives.OrderBy(
            directive => directive,
            StringComparer.Ordinal))
        {
            WriteLine($"using {usingDirective};");
        }

        BlankLine();

        if (currentNamespace is not null)
        {
            WriteLine($"namespace {currentNamespace};");
            BlankLine();
        }
    }

    public void WriteLine(string? text = null)
    {
        if (!string.IsNullOrEmpty(text))
        {
            output.Append(string.Concat(Enumerable.Repeat(IndentText, indentation)));
            output.Append(text);
        }

        output.Append('\n');
    }

    public void BlankLine() => WriteLine();

    public void WriteComment(string text) => WriteLine($"// {text}");

    public void WriteXmlSummary(string text)
    {
        WriteLine("/// <summary>");
        WriteLine($"/// {text}");
        WriteLine("/// </summary>");
    }

    public void WriteXmlParam(string name, string description) =>
        WriteLine($"/// <param name=\"{name}\">{description}</param>");

    public void WriteXmlReturns(string description) =>
        WriteLine($"/// <returns>{description}</returns>");

    public void WriteXmlInheritdoc() => WriteLine("/// <inheritdoc />");

    public void OpenBlock(string declaration)
    {
        WriteLine(declaration);
        OpenBrace();
    }

    public void OpenBrace()
    {
        WriteLine("{");
        indentation++;
    }

    public void CloseBlock(string suffix = "")
    {
        indentation--;
        WriteLine("}" + suffix);
    }

    public void Indent() => indentation++;

    public void Unindent() => indentation--;

    public override string ToString() => output.ToString();
}
