using Wireloom.Dds.Idl.Compiler.FrontEnd.Semantic;
using Wireloom.Dds.CSharp.Compiler.Naming;

namespace Wireloom.Dds.CSharp.Compiler.Emission.Planning;

/// <summary>Rejects bound type shapes whose native APIs are unavailable in the selected RTI profile.</summary>
internal static class RtiProfileValidator
{
    /// <summary>Reports profile errors before any documents are emitted, including for included declarations.</summary>
    internal static bool Validate(IReadOnlyList<IdlDeclaration> declarations, RtiApiProfile profile, ICollection<IdlDiagnostic>? diagnostics)
    {
        if (profile is { SupportsRecursiveTypes: true, SupportsOptionalCollections: true })
        {
            return true;
        }

        var aggregates = new Dictionary<string, IReadOnlyList<IdlMember>>(StringComparer.Ordinal);
        foreach (var declaration in declarations)
        {
            switch (declaration)
            {
                case IdlClassDeclaration structure:
                    aggregates.Add(IdlNaming.ResolveTypeName(structure.Name, structure.Namespace),
                        structure.Fields.Concat(structure.InheritedFields).ToArray());
                    break;
                case IdlUnionDeclaration union:
                    aggregates.Add(IdlNaming.ResolveTypeName(union.Declaration.Name, union.Declaration.Namespace),
                        union.Declaration.Branches.Select(branch => branch.Field).ToArray());
                    break;
            }
        }

        var valid = true;
        foreach (var aggregate in aggregates)
        {
            foreach (var member in aggregate.Value)
            {
                var type = UnwrapAlias(member.Type);
                if (!profile.SupportsOptionalCollections && member.Metadata.IsOptional
                    && type is IdlType.Sequence or IdlType.Array)
                {
                    Report(member, "Optional sequences and arrays");
                }

                if (!profile.SupportsRecursiveTypes && GetAggregateName(member.Type) is { } target
                    && CanReach(target, aggregate.Key, aggregates))
                {
                    Report(member, "Recursive aggregate types");
                }
            }
        }

        return valid;

        void Report(IdlMember member, string feature)
        {
            valid = false;
            if (member.SourceInput is not null)
            {
                diagnostics?.Add(new IdlDiagnostic("DDSG0004", member.SourceInput, member.SourceOffset,
                    $"{feature} are not supported by the RTI {profile.RtiVersion} API profile generated by rtiddsgen {profile.RtiddsgenVersion}."));
            }
        }
    }

    private static IdlType UnwrapAlias(IdlType type)
    {
        while (type is IdlType.Alias alias)
        {
            type = alias.Target;
        }

        return type;
    }

    private static string? GetAggregateName(IdlType type) => UnwrapAlias(type) switch
    {
        IdlType.Struct structure => structure.QualifiedName,
        IdlType.Union union => union.QualifiedName,
        IdlType.Sequence sequence => GetAggregateName(sequence.Element),
        IdlType.Array array => GetAggregateName(array.Element),
        _ => null,
    };

    private static bool CanReach(string start, string owner, IReadOnlyDictionary<string, IReadOnlyList<IdlMember>> aggregates)
    {
        var pending = new Stack<string>();
        var visited = new HashSet<string>(StringComparer.Ordinal);
        pending.Push(start);

        while (pending.Count > 0)
        {
            var current = pending.Pop();
            if (current == owner)
            {
                return true;
            }

            if (!visited.Add(current) || !aggregates.TryGetValue(current, out var members))
            {
                continue;
            }

            foreach (var member in members)
            {
                if (GetAggregateName(member.Type) is { } target)
                {
                    pending.Push(target);
                }
            }
        }

        return false;
    }
}
