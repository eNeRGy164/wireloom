using Wireloom.Dds.CSharp.Compiler.Emission;
using Wireloom.Dds.Idl.Compiler.FrontEnd;
using Wireloom.Dds.CSharp.Compiler.Emission.Planning;
using Wireloom.Dds.CSharp.Compiler.Naming;

namespace Wireloom.Dds.CSharp.Compiler;

/// <summary>Coordinates input traversal, declaration parsing, and emission.</summary>
internal sealed class IdlCompilation(IReadOnlyList<IdlInput> inputs, RtiApiProfile profile, Func<byte[], byte[]> computeMd5, CancellationToken cancellationToken)
{
    /// <summary>Analyzes IDL with C# compatibility checks and emits the selected RTI .NET mapping.</summary>
    public IReadOnlyList<GeneratedIdlSource> Run(ICollection<IdlDiagnostic>? diagnostics = null)
    {
        var identities = new GeneratedIdentitySet();
        var analysis = IdlAnalysis.Analyze(inputs, computeMd5, cancellationToken, diagnostics,
            new CSharpAnalysisChecks(identities));
        var declarations = analysis.Declarations;
        var symbols = analysis.Symbols;
        var result = new EmissionResult();
        var compilation = new CompilationContext(symbols, profile);

        if (!RtiProfileValidator.Validate(declarations, profile, diagnostics))
        {
            return [];
        }

        if (!profile.SupportsMustUnderstand)
        {
            foreach (var member in declarations
                         .SelectMany(GetMembers)
                         .Where(member => member.Metadata.IsMustUnderstand && member.SourceInput is not null))
            {
                diagnostics?.Add(new IdlDiagnostic(
                    "DDSG0004",
                    member.SourceInput!,
                    member.SourceOffset,
                    $"The @must_understand annotation is not supported by the RTI {profile.RtiVersion} API profile generated by rtiddsgen {profile.RtiddsgenVersion}."));
            }

            if (declarations.SelectMany(GetMembers).Any(member => member.Metadata.IsMustUnderstand))
            {
                return [];
            }
        }

        var sequenceArrays = new SequenceArrayEmissionPlan(compilation, symbols, declarations, profile, identities);
        return new IdlDeclarationEmitter(compilation, declarations, result, profile, sequenceArrays).Emit();
    }

    private static IEnumerable<Wireloom.Dds.Idl.Compiler.FrontEnd.Semantic.IdlMember> GetMembers(Wireloom.Dds.Idl.Compiler.FrontEnd.Semantic.IdlDeclaration declaration) => declaration switch
    {
        Wireloom.Dds.Idl.Compiler.FrontEnd.Semantic.IdlClassDeclaration classDeclaration => classDeclaration.Fields,
        Wireloom.Dds.Idl.Compiler.FrontEnd.Semantic.IdlUnionDeclaration unionDeclaration => unionDeclaration.Declaration.Branches.Select(branch => branch.Field),
        _ => []
    };
}
